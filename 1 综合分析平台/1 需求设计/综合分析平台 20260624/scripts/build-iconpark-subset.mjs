#!/usr/bin/env node
/**
 * Build assets/lib/iconpark-subset.js from js/demo-icon-map.js + @icon-park/svg (outline).
 */
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const require = createRequire(import.meta.url);

const mapPath = path.join(root, 'js', 'demo-icon-map.js');
const mapSrc = fs.readFileSync(mapPath, 'utf8');
const mapFn = new Function(`${mapSrc}; return DEMO_ICON_MAP;`);
const { LOGICAL_TO_ICONPARK } = mapFn();

const uniquePark = [...new Set(Object.values(LOGICAL_TO_ICONPARK))].sort();
const icons = {};
/** IconPark outline stroke (maps to stroke-width in 48×48 viewBox). */
const OUTLINE_STROKE_WIDTH = 4;

function normalizeSvg(svg) {
  let s = svg;
  // Keep fill="none" for outline hollow shapes; only tint real fills/strokes.
  s = s.replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"');
  s = s.replace(/stroke="[^"]*"/g, 'stroke="currentColor"');
  s = s.replace(/stroke-width="[^"]*"/g, `stroke-width="${OUTLINE_STROKE_WIDTH}"`);
  const viewBoxMatch = s.match(/viewBox="([^"]+)"/);
  const inner = s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return {
    viewBox: viewBoxMatch ? viewBoxMatch[1] : '0 0 48 48',
    body: inner.trim(),
  };
}

for (const parkName of uniquePark) {
  try {
    const mod = require(`@icon-park/svg/lib/icons/${parkName}.js`);
    const iconFn = mod.default || mod;
    if (typeof iconFn !== 'function') {
      console.warn(`No export for ${parkName}`);
      continue;
    }
    const svg = iconFn({
      theme: 'outline',
      size: 24,
      fill: '#333',
      strokeWidth: OUTLINE_STROKE_WIDTH,
    });
    icons[parkName] = normalizeSvg(svg);
  } catch (e) {
    console.warn(`Failed ${parkName}:`, e.message);
  }
}

const out = `/* Generated by scripts/build-iconpark-subset.mjs — do not edit */
(function (global) {
  global.ICONPARK_ICONS = ${JSON.stringify(icons, null, 2)};
})(typeof window !== 'undefined' ? window : globalThis);
`;

const outPath = path.join(root, 'assets', 'lib', 'iconpark-subset.js');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);

let noneCount = 0;
for (const { body } of Object.values(icons)) {
  noneCount += (body.match(/fill="none"/g) || []).length;
}
if (noneCount === 0) {
  console.warn('Warning: no fill="none" in subset — outline hollow shapes may be broken');
}

console.log(`Wrote ${Object.keys(icons).length} icons to ${path.relative(root, outPath)} (${noneCount} fill="none" paths)`);
